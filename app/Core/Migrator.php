<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Applies database/migrations/*.sql in name order and records them in schema_migrations.
 * An applied migration must never be edited: checksums are compared on every run.
 * On shared hosting without SSH, `bin/migrate.php --print` produces a single SQL
 * script to import in phpMyAdmin.
 */
final class Migrator
{
    public function __construct(private Database $db, private string $dir) {}

    public static function trackingTableSql(): string
    {
        return 'CREATE TABLE IF NOT EXISTS `schema_migrations` ('
            . '`migration` VARCHAR(190) NOT NULL PRIMARY KEY, '
            . '`checksum` CHAR(64) NOT NULL, '
            . '`applied_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP'
            . ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci';
    }

    /** @return array<string, string> migration name => absolute path */
    public function files(): array
    {
        $files = [];
        foreach (glob($this->dir . '/*.sql') ?: [] as $path) {
            $files[basename($path, '.sql')] = $path;
        }
        ksort($files, SORT_STRING);

        return $files;
    }

    /** @return array<string, string> migration name => checksum */
    public function applied(): array
    {
        $this->db->execute(self::trackingTableSql());
        $rows = $this->db->fetchAll('SELECT migration, checksum FROM schema_migrations');
        $applied = [];
        foreach ($rows as $row) {
            $applied[(string) $row['migration']] = (string) $row['checksum'];
        }

        return $applied;
    }

    /** @return list<string> applied migrations whose file changed since */
    public function modifiedSinceApplied(): array
    {
        $files = $this->files();
        $modified = [];
        foreach ($this->applied() as $name => $checksum) {
            if (isset($files[$name]) && !hash_equals($checksum, $this->checksum($files[$name]))) {
                $modified[] = $name;
            }
        }

        return $modified;
    }

    /**
     * @param callable(string): void $output
     *
     * @return int number of migrations applied
     */
    public function migrate(callable $output): int
    {
        $applied = $this->applied();
        $count = 0;
        foreach ($this->files() as $name => $path) {
            if (isset($applied[$name])) {
                continue;
            }
            $output('Applying ' . $name);
            // MySQL DDL statements commit implicitly: a failure leaves the
            // migration unrecorded so it can be fixed (new file) and rerun.
            foreach (self::splitStatements((string) file_get_contents($path)) as $statement) {
                $this->db->execute($statement);
            }
            $this->db->execute(
                'INSERT INTO schema_migrations (migration, checksum) VALUES (?, ?)',
                [$name, $this->checksum($path)],
            );
            ++$count;
        }

        return $count;
    }

    /** Full SQL script (tracking table + every migration + bookkeeping) for phpMyAdmin. */
    public function toSql(): string
    {
        $sql = '-- F2S Pro — generated by bin/migrate.php --print on ' . gmdate('c') . "\n";
        $sql .= "-- Import in phpMyAdmin on an EMPTY database, or run only the pending parts.\n\n";
        $sql .= self::trackingTableSql() . ";\n\n";
        foreach ($this->files() as $name => $path) {
            $sql .= "-- >>> {$name}\n";
            foreach (self::splitStatements((string) file_get_contents($path)) as $statement) {
                $sql .= $statement . ";\n";
            }
            $sql .= sprintf(
                "INSERT INTO schema_migrations (migration, checksum) VALUES ('%s', '%s');\n\n",
                $name,
                $this->checksum($path),
            );
        }

        return $sql;
    }

    /** @return list<string> */
    public static function splitStatements(string $sql): array
    {
        $lines = preg_split('/\R/', $sql) ?: [];
        $lines = array_filter($lines, static fn(string $l): bool => !preg_match('/^\s*--/', $l));
        $parts = preg_split('/;\s*(?:\R|$)/', implode("\n", $lines)) ?: [];

        return array_values(array_filter(array_map('trim', $parts), static fn(string $s): bool => $s !== ''));
    }

    private function checksum(string $path): string
    {
        return hash('sha256', str_replace("\r\n", "\n", (string) file_get_contents($path)));
    }
}
